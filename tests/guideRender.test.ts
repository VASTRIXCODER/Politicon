import { describe, expect, it, vi } from 'vitest';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { createElement as h } from 'react';
import { renderToString } from 'react-dom/server';
import { GUARDRAIL_REPLIES } from '@/lib/guardrails';
import type { ExtendedMessage } from '@/app/advisor/_components/types';
import type { RailPolicy } from '@/components/guide/policyRail';

// The Chamber's markup as the server (and a first client render) draws it:
// the accessible names, roles and texts the journey e2e and screen readers
// depend on, the calm seal cards, the rail's keyboard path, and the orb as
// decoration only.

const search = { params: new URLSearchParams() };
vi.mock('next/navigation', () => ({
  useRouter: () => ({ push: () => {}, replace: () => {}, prefetch: () => {} }),
  usePathname: () => '/advisor',
  useSearchParams: () => search.params,
}));

const { default: MessagePane, TypingPane } = await import('@/app/advisor/_components/MessagePane');
const { default: PolicyRail, PolicyChip } = await import('@/app/advisor/_components/PolicyRail');
const { default: Composer } = await import('@/app/advisor/_components/Composer');
const { default: ChamberFallback } = await import('@/app/advisor/_components/ChamberFallback');
const { default: AdvisorChamber } = await import('@/app/advisor/_components/AdvisorChamber');
const { default: OrbPoster } = await import('@/components/guide/OrbPoster');

const AT = new Date('2026-10-18T09:30:00Z');
const pane = (message: ExtendedMessage, sessionId: string | null = 'session-1', onRetry?: () => void) =>
  renderToString(h(MessagePane, { message, sessionId, onRetry }));
const text = (html: string) => html.replace(/<!-- -->/g, '').replace(/<[^>]+>/g, ' ').replace(/&#x27;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/\s+/g, ' ');

const CHIP: RailPolicy = {
  id: 'us-119-hr-1001',
  title: 'Working Families Tax Credit Act',
  category: 'taxes',
  relevanceScore: 86,
  direction: 'positive',
  estimatedImpact: '+$1,200/yr',
  source: 'feed',
};

describe('message panes', () => {
  it('the user’s message: "You said:" for screen readers only, and no rating buttons', () => {
    const html = pane({ id: '1', role: 'user', content: 'How would a minimum wage increase affect me?', timestamp: AT });
    expect(html).toContain('<span class="sr-only">You said: </span>');
    expect(text(html)).toContain('How would a minimum wage increase affect me?');
    expect(html).not.toContain('Helpful');
    expect(html).toContain('data-message="user"');
  });

  it('a saved model reply: "Policy Guide said:", the dollar line on a solid pane, and Helpful', () => {
    const html = pane({
      id: '2', role: 'assistant', content: 'Summary.\n\n+$600 to $1,200/yr', summary: 'Summary.', dollarLine: '+$600 to $1,200/yr', timestamp: AT,
    });
    expect(html).toContain('<span class="sr-only">Policy Guide said: </span>');
    expect(text(html)).toContain('+$600 to $1,200/yr');
    expect(html).toContain('aria-label="Helpful"');
    expect(html).not.toContain('Try again');
    // The dollar line has no known direction: violet, never the gain/loss pair.
    expect(html).toMatch(/<p class="font-mono-data[^"]*text-primary-300">\+\$600 to \$1,200\/yr<\/p>/);
  });

  it('an unsaved reply has no rating buttons', () => {
    const html = pane({ id: '3', role: 'assistant', content: 'Hi.', timestamp: AT }, null);
    expect(html).not.toContain('Helpful');
  });

  for (const kind of ['vote_advice', 'crisis'] as const) {
    it(`a ${kind} guardrail reply is a calm seal card: its text unchanged, no rating, no error colour`, () => {
      const html = pane({ id: `g-${kind}`, role: 'assistant', content: GUARDRAIL_REPLIES[kind], guardrail: kind, timestamp: AT });
      expect(html).toContain(`data-guardrail="${kind}"`);
      expect(html).toContain('<span class="sr-only">Policy Guide said: </span>');
      // The reply's text exactly (paragraph breaks kept by whitespace-pre-wrap).
      const body = html.match(/<p class="mt-3\.5 whitespace-pre-wrap[^"]*">([\s\S]*?)<\/p>/)?.[1];
      expect(text(body ?? '').trim()).toBe(GUARDRAIL_REPLIES[kind].replace(/\s+/g, ' ').trim());
      expect(text(html)).toContain('A fixed reply, written in advance, not generated by AI.');
      expect(html).not.toContain('Helpful');
      expect(html).not.toContain('Try again');
      // Calm: never the error colour, and never the official record's gold.
      expect(html).not.toMatch(/class="[^"]*(danger|gold)[^"]*"/);
    });
  }

  it('an error bubble offers "Try again" only when it can be retried', () => {
    const error: ExtendedMessage = { id: '9', role: 'assistant', local: true, content: 'The guide is busy.', retry: { text: 'Hello' }, timestamp: AT };
    expect(pane(error, 's', () => {})).toContain('>Try again</button>');
    expect(pane(error, 's')).not.toContain('Try again');
    expect(pane({ ...error, retry: undefined }, 's', () => {})).not.toContain('Try again');
    // Errors are never rated.
    expect(pane(error, 's', () => {})).not.toContain('Helpful');
  });

  it('the greeting is neither an error nor rated', () => {
    const html = pane({ id: '0', role: 'assistant', local: true, content: 'Hi!', timestamp: AT });
    expect(html).toContain('data-message="guide"');
    expect(html).not.toContain('Helpful');
  });

  it('the typing pane says so to screen readers, with decorative dots', () => {
    const html = renderToString(h(TypingPane));
    expect(html).toContain('The Policy Guide is typing…');
    expect(html).toMatch(/<div aria-hidden="true" class="flex items-center gap-1\.5">/);
  });
});

describe('the "Your policies" rail', () => {
  it('each chip can be dragged, and asked about with a button that names the policy', () => {
    const html = renderToString(h(PolicyChip, { policy: CHIP, onAsk: () => {} }));
    expect(html).toMatch(/<li draggable="true"/);
    expect(text(html)).toContain('Ask about this policy : Working Families Tax Credit Act');
    expect(html).toMatch(/<button type="button"[^>]*>.*Ask about this policy<span class="sr-only">: (<!-- -->)?Working Families Tax Credit Act<\/span><\/button>/);
    expect(text(html)).toContain('Relevance 86 out of 100.');
    expect(text(html)).toMatch(/Likely helps you ?\./);
  });

  it('an analysed policy shows the user’s estimate with its sign and words, in teal or amber', () => {
    const gain = renderToString(h(PolicyChip, { policy: { ...CHIP, analysedAnnual: 1200 }, onAsk: () => {} }));
    expect(text(gain)).toMatch(/Your estimate \+\$1,200\/yr saves you/);
    expect(gain).toContain('text-gain');
    const cost = renderToString(h(PolicyChip, { policy: { ...CHIP, direction: undefined, analysedAnnual: -340, source: 'analysis' }, onAsk: () => {} }));
    expect(text(cost)).toMatch(/Your estimate −\$340\/yr costs you/);
    expect(cost).toContain('text-loss');
    expect(text(cost)).toContain('Analyzed');
  });

  it('says when there is nothing to list, and when it is loading', () => {
    expect(text(renderToString(h(PolicyRail, { policies: [], loading: false, onAsk: () => {} })))).toContain('No policies in your feed yet.');
    expect(renderToString(h(PolicyRail, { policies: [], loading: true, onAsk: () => {} }))).toContain('Loading your policies…');
  });
});

describe('the composer', () => {
  it('keeps the journey’s names, and says which policy a prefilled question is about', () => {
    const html = renderToString(
      h(Composer, {
        value: 'Tell me about the financial impact of X',
        onChange: () => {},
        onSubmit: () => {},
        disabled: false,
        inputRef: { current: null },
        pendingPolicy: { policyId: 'x', policyTitle: 'X Act' },
        onClearPolicy: () => {},
        onDropPolicy: () => {},
      })
    );
    expect(html).toContain('aria-label="Message the Policy Guide"');
    expect(html).toContain('aria-label="Send message"');
    expect(text(html)).toContain('About X Act');
    expect(html).toContain('aria-label="Don’t ask about X Act"');
  });
});

describe('the Chamber', () => {
  it('the orb is decoration: hidden from screen readers, its state on a data attribute', () => {
    const html = renderToString(h(OrbPoster, { state: 'thinking' }));
    expect(html).toMatch(/^<div aria-hidden="true" data-decorative="" data-state="thinking"/);
  });

  it('the prerendered fallback shows the title and the orb, and is busy', () => {
    const html = renderToString(h(ChamberFallback));
    expect(html).toContain('aria-busy="true"');
    expect(html).toMatch(/<h1[^>]*>AI Policy <em[^>]*>Guide<\/em><\/h1>/);
    expect(html).toContain('Loading the Policy Guide…');
  });

  it('renders the conversation with every journey selector, and no "You said:" before anything is sent', () => {
    const html = renderToString(h(AdvisorChamber));
    expect(html).toMatch(/<h1[^>]*>AI Policy <em[^>]*>Guide<\/em><\/h1>/);
    expect(html).toMatch(/role="log" aria-live="polite" aria-relevant="additions" aria-label="Conversation"/);
    expect(html).toContain('aria-label="Message the Policy Guide"');
    expect(html).toContain('aria-label="Send message"');
    expect(html).toContain('role="group" aria-label="Suggested questions"');
    expect(html).not.toContain('You said:');
    // The greeting is the one guide message.
    expect(html.match(/Policy Guide said:/g)).toHaveLength(1);
    // The orb's poster is server-rendered, and decorative.
    expect(html).toContain('data-state="idle"');
  });

  it('never asks with window.confirm or alert', () => {
    const dir = path.resolve(__dirname, '../app/advisor');
    const files = ['page.tsx', ...['AdvisorChamber', 'useGuideConversation', 'Composer', 'ConversationList', 'MessagePane', 'PolicyRail', 'OrbDock'].map((f) => `_components/${f}.${f.startsWith('use') ? 'ts' : 'tsx'}`)];
    for (const f of files) {
      const src = readFileSync(path.join(dir, f), 'utf8');
      expect(src, f).not.toMatch(/window\.(confirm|alert)\(/);
    }
  });
});
