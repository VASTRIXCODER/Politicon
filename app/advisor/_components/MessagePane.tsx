import { AlertCircle, DollarSign, Loader2 } from 'lucide-react';
import ViewFullImpactButton from '@/components/ViewFullImpactButton';
import FeedbackControls from '@/components/FeedbackControls';
import GuideSeal from '@/components/guide/GuideSeal';
import { MiniOrb } from '@/components/guide/OrbPoster';
import styles from '@/components/guide/guide.module.css';
import { cn } from '@/lib/utils';
import { INITIAL_MESSAGE, type ExtendedMessage } from './types';

/*
 * The conversation as panes of glass at depth, in the Chamber's night:
 * the user's on the right in violet-tinted glass, the guide's on the left in
 * night glass with a thin edge of violet light and its small orb beside
 * them. Each rises out of the dark as it arrives (CSS, still under reduced
 * motion). The panes are near-opaque, so text keeps its contrast over the
 * aurora, and solid where people ask for less transparency; figures (the
 * dollar line) sit on a solid pane inside them.
 *
 * The guide's fixed replies (guardrails: voting advice, a crisis) are calm
 * seal cards, distinct from model replies and never alarming: a violet seal,
 * a plain label saying it is a fixed reply, and the reply's text unchanged.
 * Error bubbles carry a "Try again" when the request can be retried.
 *
 * Screen readers hear "You said:" or "Policy Guide said:" before each
 * message (visually hidden), and the message's text exactly as it arrived.
 */

const PANE = 'relative px-5 py-3.5 text-sm leading-relaxed shadow-[inset_0_1px_0_rgb(255_255_255/0.07),0_22px_44px_-22px_rgb(0_0_0/0.85)]';

/**
 * The guide's panes: night glass with a hairline rim, nearly opaque (and
 * solid for less transparency). No backdrop blur: a conversation holds many
 * panes, and blurring behind each would cost every scrolled frame on a phone.
 */
const GUIDE_PANE = cn(
  PANE,
  'rounded-[1.25rem] rounded-tl-md border border-fg/10 bg-surface/[0.92] text-ink',
  '[@media(prefers-reduced-transparency:reduce)]:bg-surface'
);

/** The user's panes: raised night glass tinted violet. */
const USER_PANE = cn(
  PANE,
  'rounded-[1.25rem] rounded-tr-md border border-primary/30 bg-raised text-ink',
  'bg-[linear-gradient(160deg,rgb(var(--c-violet)/0.26),rgb(var(--c-violet)/0.1))]'
);

/** Labels for the seal cards, by guardrail kind. */
const SEAL_LABEL: Record<string, string> = {
  vote_advice: 'Non-partisan by design',
  crisis: 'Support is available',
};

function time(t: Date | string) {
  return new Date(t).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
}

export default function MessagePane({ message, sessionId, onRetry }: {
  message: ExtendedMessage;
  sessionId: string | null;
  onRetry?: (_m: ExtendedMessage) => void;
}) {
  const isUser = message.role === 'user';
  const isModelReply = !isUser && !message.local && !message.guardrail;
  const isPolicyReply = !isUser && (!!message.dollarLine || !!message.policyId);
  const isError = !isUser && !!message.local && message.id !== INITIAL_MESSAGE.id;

  if (isUser) {
    return (
      <div className={cn(styles.pane, 'mb-4 flex justify-end')} data-message="user">
        <div className={cn(USER_PANE, 'max-w-[85%] sm:max-w-[78%]')}>
          <span className="sr-only">You said: </span>
          <p className="whitespace-pre-wrap break-words">{message.content}</p>
          <p className="mt-2 text-meta text-muted">{time(message.timestamp)}</p>
        </div>
      </div>
    );
  }

  if (message.guardrail) {
    return (
      <div className={cn(styles.pane, 'mb-4 flex items-end gap-3')} data-message="guardrail" data-guardrail={message.guardrail}>
        <MiniOrb className="mb-1" />
        <div className={cn(PANE, 'max-w-[85%] rounded-[1.25rem] rounded-tl-md border border-primary/25 bg-raised py-4 text-ink sm:max-w-[78%]')}>
          {/* A rim of violet light along the top edge: the seal's light. */}
          <span aria-hidden="true" className="pointer-events-none absolute inset-x-8 top-0 h-px bg-gradient-to-r from-transparent via-primary/60 to-transparent" />
          <span className="sr-only">Policy Guide said: </span>
          <div className="flex items-center gap-3.5">
            <GuideSeal />
            <div className="min-w-0">
              <p className="text-meta font-semibold uppercase tracking-[0.14em] text-primary-300">{SEAL_LABEL[message.guardrail] ?? 'A note from the guide'}</p>
              <p className="mt-0.5 text-meta text-muted">A fixed reply, written in advance, not generated by AI.</p>
            </div>
          </div>
          <p className="mt-3.5 whitespace-pre-wrap break-words">{message.content}</p>
          <p className="mt-2 text-meta text-muted">{time(message.timestamp)}</p>
        </div>
      </div>
    );
  }

  return (
    <div className={cn(styles.pane, 'mb-4 flex items-end gap-3')} data-message={isError ? 'error' : 'guide'}>
      <MiniOrb className="mb-1" />
      <div className={cn(GUIDE_PANE, styles.lightEdge, 'max-w-[85%] sm:max-w-[78%]', isError && 'border-danger/30')}>
        <span className="sr-only">Policy Guide said: </span>
        {isPolicyReply ? (
          <>
            <p className="whitespace-pre-wrap break-words">{message.summary || message.content}</p>
            {message.dollarLine && (
              // A free-text, hedged estimate with no known direction: violet, not gain/loss (or the record's gold).
              <div className="mt-3 flex items-start gap-2.5 rounded-xl border border-primary/25 bg-raised px-4 py-3">
                <DollarSign className="mt-0.5 h-4 w-4 flex-shrink-0 text-primary-300" aria-hidden="true" />
                <p className="font-mono-data text-sm font-medium leading-snug text-primary-300">{message.dollarLine}</p>
              </div>
            )}
            {message.compiling && (
              <div className="mt-3 flex items-center gap-2 text-xs text-muted">
                <Loader2 className="h-3 w-3 text-primary motion-safe:animate-spin" aria-hidden="true" /> Compiling full analysis…
              </div>
            )}
            {message.policyId && (
              <ViewFullImpactButton
                policyId={message.policyId}
                policyTitle={message.policyTitle || message.policyId}
                category={message.category}
                description={message.summary}
                variant="chat"
              />
            )}
          </>
        ) : (
          <p className="whitespace-pre-wrap break-words">
            {isError && <AlertCircle className="-mt-0.5 mr-1.5 inline h-4 w-4 text-danger" aria-hidden="true" />}
            {message.content}
          </p>
        )}
        {message.retry && onRetry && (
          <button
            type="button"
            onClick={() => onRetry(message)}
            className="mt-3 inline-flex items-center gap-1.5 rounded-full border border-primary/30 px-3 py-1.5 text-xs font-medium text-primary-300 transition-colors hover:border-primary/50 hover:text-ink"
          >
            Try again
          </button>
        )}
        <p className="mt-2 text-meta text-muted">{time(message.timestamp)}</p>
        {/* Rated replies are tied to a saved conversation, with a copy of the reply's start. */}
        {isModelReply && sessionId && (
          <FeedbackControls
            targetType="chat_reply"
            targetId={`${sessionId}:${message.id}`}
            excerpt={message.content.slice(0, 500)}
            className="mt-1"
          />
        )}
      </div>
    </div>
  );
}

/** The guide's pane while a reply is on its way. */
export function TypingPane() {
  return (
    <div className={cn(styles.pane, 'mb-4 flex items-end gap-3')}>
      <MiniOrb className="mb-1" />
      <div className={cn(GUIDE_PANE, styles.lightEdge, 'px-5 py-4')}>
        <span className="sr-only">The Policy Guide is typing…</span>
        <div aria-hidden="true" className="flex items-center gap-1.5">
          <span className={styles.dot} />
          <span className={styles.dot} />
          <span className={styles.dot} />
        </div>
      </div>
    </div>
  );
}
